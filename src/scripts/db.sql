BEGIN;

CREATE SCHEMA IF NOT EXISTS food_bank;

SET LOCAL search_path TO food_bank, public;

-- 1. Users
CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    phone VARCHAR(20) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL
        CHECK (role IN (
            'Donor', 'Recipient', 'Volunteer', 'Coordinator'
        )),
    failed_logins SMALLINT NOT NULL DEFAULT 0
        CHECK (failed_logins >= 0),
    locked_until TIMESTAMP,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower
ON users (LOWER(email));


-- 2. Recipients
CREATE TABLE IF NOT EXISTS recipients (
    recipient_id INTEGER PRIMARY KEY
        REFERENCES users(user_id) ON DELETE RESTRICT,
    household_size INTEGER NOT NULL
        CHECK (household_size > 0),
    dietary_restrictions VARCHAR(255),
    emergency_contact VARCHAR(150) NOT NULL,
    approval_status VARCHAR(12) NOT NULL DEFAULT 'Pending'
        CHECK (approval_status IN (
            'Pending', 'Approved', 'Rejected'
        )),
    approved_by INTEGER
        REFERENCES users(user_id) ON DELETE RESTRICT,
    approved_at TIMESTAMP
);


-- 3. Volunteers
CREATE TABLE IF NOT EXISTS volunteers (
    volunteer_id INTEGER PRIMARY KEY
        REFERENCES users(user_id) ON DELETE RESTRICT,
    profile_image VARCHAR(255),
    availability VARCHAR(255),
    created_by INTEGER
        REFERENCES users(user_id) ON DELETE RESTRICT
);


-- 4. Categories
CREATE TABLE IF NOT EXISTS categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_categories_name_lower
ON categories (LOWER(name));


-- 5. Donations
CREATE TABLE IF NOT EXISTS donations (
    donation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_id INTEGER NOT NULL
        REFERENCES users(user_id) ON DELETE RESTRICT,
    recorded_by INTEGER NOT NULL
        REFERENCES users(user_id) ON DELETE RESTRICT,
    item_name VARCHAR(100) NOT NULL,
    category_id INTEGER NOT NULL
        REFERENCES categories(category_id) ON DELETE RESTRICT,
    quantity NUMERIC(10,2) NOT NULL
        CHECK (quantity > 0),
    unit VARCHAR(20) NOT NULL,
    donation_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'CREATED'
        CHECK (status IN (
            'CREATED', 'PENDING', 'COMPLETED', 'FAILED'
        ))
);


-- 6. Inventory
CREATE TABLE IF NOT EXISTS inventory (
    inventory_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donation_id INTEGER
        REFERENCES donations(donation_id) ON DELETE RESTRICT,
    item_name VARCHAR(100) NOT NULL,
    category_id INTEGER NOT NULL
        REFERENCES categories(category_id) ON DELETE RESTRICT,
    quantity NUMERIC(10,2) NOT NULL
        CHECK (quantity >= 0),
    quantity_received NUMERIC(10,2) NOT NULL
        CHECK (quantity_received >= 0),
    unit VARCHAR(20) NOT NULL,
    received_date DATE NOT NULL DEFAULT CURRENT_DATE,
    expiry_date DATE,
    waste_date DATE,
    status VARCHAR(12) NOT NULL DEFAULT 'Available'
        CHECK (status IN (
            'Available', 'Distributed', 'Expired', 'Discarded'
        )),
    updated_by INTEGER
        REFERENCES users(user_id) ON DELETE RESTRICT
);


-- 7. Hamper requests
CREATE TABLE IF NOT EXISTS hamper_requests (
    request_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id INTEGER NOT NULL
        REFERENCES recipients(recipient_id) ON DELETE RESTRICT,
    request_date DATE NOT NULL DEFAULT CURRENT_DATE,
    pickup_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN (
            'PENDING', 'SCHEDULED', 'FULFILLED', 'CANCELLED'
        ))
);


-- 8. Distributions
CREATE TABLE IF NOT EXISTS distributions (
    distribution_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id INTEGER NOT NULL UNIQUE
        REFERENCES hamper_requests(request_id) ON DELETE RESTRICT,
    volunteer_id INTEGER
        REFERENCES volunteers(volunteer_id) ON DELETE RESTRICT,
    distribution_date DATE NOT NULL,
    pickup_time TIME,
    pickup_status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED'
        CHECK (pickup_status IN (
            'SCHEDULED', 'FULFILLED', 'MISSED', 'DELAYED'
        ))
);


-- 9. Distribution items
CREATE TABLE IF NOT EXISTS distribution_items (
    distribution_item_id INTEGER
        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distribution_id INTEGER NOT NULL
        REFERENCES distributions(distribution_id) ON DELETE CASCADE,
    inventory_id INTEGER NOT NULL
        REFERENCES inventory(inventory_id) ON DELETE RESTRICT,
    quantity NUMERIC(10,2) NOT NULL
        CHECK (quantity > 0),
    unit VARCHAR(20) NOT NULL
);


-- 10. Volunteer shifts
CREATE TABLE IF NOT EXISTS volunteer_shifts (
    shift_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    volunteer_id INTEGER NOT NULL
        REFERENCES volunteers(volunteer_id) ON DELETE RESTRICT,
    coordinator_id INTEGER NOT NULL
        REFERENCES users(user_id) ON DELETE RESTRICT,
    shift_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    task VARCHAR(255) NOT NULL,

    CHECK (end_time > start_time)
);


-- 11. Notifications
CREATE TABLE IF NOT EXISTS notifications (
    notification_id INTEGER
        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id INTEGER NOT NULL
        REFERENCES users(user_id) ON DELETE RESTRICT,
    recipient_email VARCHAR(150) NOT NULL,
    notification_type VARCHAR(30) NOT NULL
        CHECK (notification_type IN (
            'INVENTORY_AT_RISK',
            'MISSED_PICKUP',
            'DELAYED_PICKUP'
        )),
    reason VARCHAR(255),
    category_id INTEGER
        REFERENCES categories(category_id) ON DELETE RESTRICT,
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_sent BOOLEAN NOT NULL DEFAULT FALSE,
    sent_at TIMESTAMPTZ
);


-- 12. Inventory history
CREATE TABLE IF NOT EXISTS inventory_history (
    history_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_id INTEGER NOT NULL
        REFERENCES inventory(inventory_id) ON DELETE RESTRICT,
    category_id INTEGER NOT NULL
        REFERENCES categories(category_id) ON DELETE RESTRICT,
    unit VARCHAR(20) NOT NULL,
    quantity_change NUMERIC(10,2) NOT NULL
        CHECK (quantity_change <> 0),
    change_type VARCHAR(30) NOT NULL
        CHECK (change_type IN (
            'DONATION_RECEIVED',
            'DISTRIBUTED',
            'WASTED',
            'MANUAL_ADJUSTMENT'
        )),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE INDEX IF NOT EXISTS idx_donations_date_category ON donations (donation_date, category_id);
CREATE INDEX IF NOT EXISTS idx_distributions_date_status ON distributions (distribution_date, pickup_status);
CREATE INDEX IF NOT EXISTS idx_inventory_expiry_category ON inventory (expiry_date, category_id);
CREATE INDEX IF NOT EXISTS idx_users_name ON users (LOWER(name));
CREATE INDEX IF NOT EXISTS idx_inventory_history_time ON inventory_history (occurred_at, category_id);

COMMIT;