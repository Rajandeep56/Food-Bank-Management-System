package model;

import java.time.Instant;
import java.time.LocalDate;
import java.time.YearMonth;

import common.ReportPeriodType;

public abstract  class Report {
    private ReportPeriodType periodType;
    private LocalDate startDate;
    private LocalDate endDate;
    private boolean toDate;
    private Instant generationTime;
    private String coordinatorName;
    private boolean generated = false;

    public void specifyPeriod(ReportPeriodType periodType, int year, int month){
        if(periodType==null){
            throw new IllegalArgumentException("periodType is null");
        }
        if (year < 1 || year > LocalDate.now().getYear()) {
            throw new IllegalArgumentException("Invalid year");
        }
        LocalDate start;
        LocalDate end;
        if (periodType == ReportPeriodType.MONTHLY) {
            if (month < 1 || month > 12) {
                throw new IllegalArgumentException("Invalid month");
            }
            start = LocalDate.of(year, month, 1);
            end = YearMonth.of(year, month).atEndOfMonth();
        } else {

            start = LocalDate.of(year, 1, 1);
            end = LocalDate.of(year, 12, 31);
        }
        if (start.isAfter(LocalDate.now())) {
            throw new IllegalArgumentException(
                "Report period cannot start in the future"
            );
        }

        this.toDate = end.isAfter(LocalDate.now());

        if (this.toDate) {
            end = LocalDate.now();
        }
        this.periodType = periodType;
        this.startDate = start;
        this.endDate = end;
        this.generated = false;
    }

    public ReportPeriodType getPeriodType() {
        return periodType;
    }

    public LocalDate getStartDate() {
        return startDate;
    }

    public LocalDate getEndDate() {
        return endDate;
    }

    public boolean isToDate() {
        return toDate;
    }

    public boolean isGenerated() {
        return generated;
    }

    public void markGenerated() {
        this.generated = true;
    }

    public abstract void generate();

    public abstract void display();

    public void initializeMetadata(String coordinatorName) {
        if (coordinatorName == null || coordinatorName.isBlank()) {
            throw new IllegalArgumentException(
                "Coordinator name cannot be empty"
            );
        }

        this.coordinatorName = coordinatorName;
        this.generationTime = Instant.now();
    }
    public Instant getGenerationTime() {
        return generationTime;
    }

    public String getCoordinatorName() {
        return coordinatorName;
    }
    
    protected void displayHeader(String reportName) {
    System.out.println("=== " + reportName + " ===");

    System.out.println("Period: " + startDate + " to " 
        + endDate + (toDate ? " (To Date)" : ""));

    System.out.println("Generated At: " + generationTime);
    System.out.println("Generated By: " + coordinatorName);
    }
}
